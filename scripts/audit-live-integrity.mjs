import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = process.cwd();
const layoutPath = join(root, 'src/layouts/Layout.astro');
const headersPath = join(root, 'public/_headers');
const distDir = join(root, 'dist');

const fail = [];
const warn = [];

function read(path) {
  return existsSync(path) ? readFileSync(path, 'utf8') : '';
}

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

function count(re, text) {
  return [...text.matchAll(re)].length;
}

function preview(text, max = 180) {
  return text.replace(/\s+/g, ' ').trim().slice(0, max);
}

const layout = read(layoutPath);
const headers = read(headersPath);

if (!layout) fail.push(`Missing ${relative(root, layoutPath)}`);
if (!headers) fail.push(`Missing ${relative(root, headersPath)}`);

const beaconSrcCount = count(/https:\/\/static\.cloudflareinsights\.com\/beacon\.min\.js/g, layout);
const beaconTagCount = count(/<script\s+[^>]*type=["']module["'][^>]*src=["']https:\/\/static\.cloudflareinsights\.com\/beacon\.min\.js["'][^>]*data-cf-beacon=/g, layout);

if (beaconSrcCount !== 1) fail.push(`Expected exactly 1 Cloudflare beacon source in Layout.astro; found ${beaconSrcCount}`);
if (beaconTagCount !== 1) fail.push(`Expected exactly 1 canonical Cloudflare beacon tag in Layout.astro; found ${beaconTagCount}`);

const requiredAstroJsonLd = [
  'set:html={JSON.stringify(businessSchema)}',
  'set:html={JSON.stringify(webSiteSchema)}',
  'set:html={JSON.stringify(webPageSchema)}',
];
for (const expression of requiredAstroJsonLd) {
  if (!layout.includes(expression)) fail.push(`Missing required Astro JSON-LD expression: ${expression}`);
}

const cspScriptOk = /script-src[^\n]*https:\/\/static\.cloudflareinsights\.com/.test(headers);
const cspConnectOk = /connect-src[^\n]*https:\/\/cloudflareinsights\.com/.test(headers) || /connect-src[^\n]*https:\/\/static\.cloudflareinsights\.com/.test(headers);
if (!cspScriptOk) fail.push('CSP script-src does not allow static.cloudflareinsights.com');
if (!cspConnectOk) fail.push('CSP connect-src does not allow Cloudflare Insights');

// Astro source can legitimately contain paired JSON-LD <script> blocks whose body is
// generated by Astro expressions. Those are not literal JSON and must not be JSON.parse()'d.
// We validate literal JSON only when the body is truly static JSON.
const literalJsonLdRe = /<script\b[^>]*type=["']application\/ld\+json["'][^>]*>([\s\S]*?)<\/script>/gi;
const sourceFiles = walk(join(root, 'src')).filter((file) => /\.astro$/i.test(file));
let sourceDynamic = 0;
let sourceLiteral = 0;
let sourceLiteralBad = 0;
const sourceProblems = [];

for (const file of sourceFiles) {
  const html = read(file);
  literalJsonLdRe.lastIndex = 0;
  let match;
  while ((match = literalJsonLdRe.exec(html)) !== null) {
    const body = match[1].trim();
    const dynamic = /JSON\.stringify\s*\(|\{\s*[A-Za-z_$][\w$]*\s*\}|\$\{[\s\S]*?\}/.test(body);
    const rel = relative(root, file);
    if (dynamic) {
      sourceDynamic += 1;
      continue;
    }
    sourceLiteral += 1;
    try {
      JSON.parse(body);
    } catch (error) {
      sourceLiteralBad += 1;
      const reason = error instanceof Error ? error.message : String(error);
      sourceProblems.push(`${rel}: ${reason} :: ${preview(body)}`);
    }
  }
}

if (layout.includes('id="legalservice-schema"') || layout.includes("id='legalservice-schema'")) {
  fail.push('Obsolete legalservice-schema block remains in Layout.astro');
}

let renderedFiles = 0;
let renderedBeaconTags = 0;
let renderedJsonLd = 0;
let renderedBadJsonLd = 0;
const renderedProblems = [];

if (!existsSync(distDir)) {
  warn.push('dist/ does not exist; rendered-output checks were skipped. Run npm run build first.');
} else {
  const htmlFiles = walk(distDir).filter((file) => /\.html$/i.test(file));
  renderedFiles = htmlFiles.length;
  for (const file of htmlFiles) {
    const html = read(file);
    const rel = relative(distDir, file);
    const pageBeaconCount = count(/<script\b[^>]*src=["']https:\/\/static\.cloudflareinsights\.com\/beacon\.min\.js["'][^>]*data-cf-beacon=/g, html);
    renderedBeaconTags += pageBeaconCount;
    if (pageBeaconCount !== 1) {
      renderedProblems.push(`${rel}: expected 1 rendered Cloudflare beacon, found ${pageBeaconCount}`);
    }

    const renderedLdRe = /<script\b[^>]*type=["']application\/ld\+json["'][^>]*>([\s\S]*?)<\/script>/gi;
    renderedLdRe.lastIndex = 0;
    let match;
    while ((match = renderedLdRe.exec(html)) !== null) {
      renderedJsonLd += 1;
      const body = match[1].trim();
      if (/JSON\.stringify\s*\(|\$\{[\s\S]*?\}/.test(body)) {
        renderedBadJsonLd += 1;
        renderedProblems.push(`${rel}: rendered JSON-LD contains Astro/template syntax :: ${preview(body)}`);
        continue;
      }
      try {
        JSON.parse(body);
      } catch (error) {
        renderedBadJsonLd += 1;
        const reason = error instanceof Error ? error.message : String(error);
        renderedProblems.push(`${rel}: ${reason} :: ${preview(body)}`);
      }
    }

    if (html.includes('legalservice-schema')) {
      renderedProblems.push(`${rel}: obsolete legalservice-schema marker found in rendered HTML`);
    }
  }
}

if (sourceLiteralBad > 0) {
  for (const problem of sourceProblems) fail.push(`Literal source JSON-LD invalid: ${problem}`);
}
if (renderedProblems.length > 0) {
  for (const problem of renderedProblems.slice(0, 20)) fail.push(problem);
  if (renderedProblems.length > 20) fail.push(`... and ${renderedProblems.length - 20} additional rendered-output problem(s)`);
}

console.log('');
console.log('=== LIVE INTEGRITY QA v34 ===');
console.log(`source beacon src count: ${beaconSrcCount}`);
console.log(`source canonical beacon tag count: ${beaconTagCount}`);
console.log(`Astro JSON-LD source expressions preserved: ${requiredAstroJsonLd.filter((x) => layout.includes(x)).length}/3`);
console.log(`CSP script source allowed: ${cspScriptOk ? 'yes' : 'no'}`);
console.log(`CSP connection source allowed: ${cspConnectOk ? 'yes' : 'no'}`);
console.log(`paired JSON-LD blocks in Astro source: ${sourceDynamic + sourceLiteral}`);
console.log(`dynamic/generated JSON-LD source blocks accepted: ${sourceDynamic}`);
console.log(`literal JSON-LD source blocks parsed: ${sourceLiteral}`);
console.log(`literal malformed JSON-LD source blocks: ${sourceLiteralBad}`);
console.log(`rendered HTML files checked: ${renderedFiles}`);
console.log(`rendered beacon tags total: ${renderedBeaconTags}`);
console.log(`rendered JSON-LD blocks: ${renderedJsonLd}`);
console.log(`rendered malformed/illegal JSON-LD blocks: ${renderedBadJsonLd}`);

if (warn.length) {
  for (const item of warn) console.log(`WARN: ${item}`);
}
if (fail.length) {
  for (const item of fail) console.error(`ERROR: ${item}`);
  process.exit(1);
}
console.log('LIVE INTEGRITY QA: PASS');
