import { existsSync, readFileSync } from 'node:fs';
const errors = [];
const warnings = [];
const read = (p) => readFileSync(p, 'utf8');
if (!existsSync('public/analytics.js')) errors.push('public/analytics.js is missing');
const layout = read('src/layouts/Layout.astro');
const analytics = existsSync('public/analytics.js') ? read('public/analytics.js') : '';
const scriptLoads = (layout.match(/<script[^>]+src=["']\/?analytics\.js["'][^>]*>/gi) || []).length;
if (scriptLoads !== 1) errors.push(`Layout: analytics.js should be loaded exactly once, found ${scriptLoads}`);
if (!analytics.includes('window.zaraz.track')) errors.push('analytics.js: Zaraz event sink missing');
if (!analytics.includes("channel = 'whatsapp'")) errors.push('analytics.js: WhatsApp classification missing');
if (!analytics.includes("channel = 'email'")) errors.push('analytics.js: email classification missing');
if (!analytics.includes("channel = 'phone'")) errors.push('analytics.js: phone classification missing');
if (/new FormData|formData|querySelector\([^)]*(?:name|email|phone|message)/i.test(analytics)) warnings.push('analytics.js: review form-data access pattern');
console.log(`Analytics QA errors: ${errors.length}`);
console.log(`Analytics QA warnings: ${warnings.length}`);
for (const e of errors) console.error(`ERROR ${e}`);
for (const w of warnings) console.warn(`WARN ${w}`);
if (errors.length) process.exit(1);
